import { chromium } from 'playwright' // 真實 Chrome 逐事件核對新圖層取消、重播與卸載。

const browser = await chromium.launch({ headless: true, executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe' })
const events = async (page, label) => (await page.getByRole('status', { name: label }).innerText()).split('、').filter(value => value !== '尚無事件')
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  await page.goto('http://127.0.0.1:5174/?ui-review=components', { waitUntil: 'networkidle' })
  await page.addStyleTag({ content: '.transition-object{animation:none!important}' }) // animationend 遺失時驗證有界退路。
  const player = page.locator('section.card').filter({ has: page.getByRole('heading', { name: '轉場播放器' }) })
  await player.getByRole('button', { name: '重播', exact: true }).click()
  await player.getByRole('button', { name: '重播', exact: true }).click()
  await page.waitForTimeout(800)
  let log = await events(page, '轉場事件紀錄')
  if (log.filter(value => value === 'page:start').length !== 2 || log.filter(value => value === 'page:cancel').length !== 1 || log.filter(value => value === 'page:complete').length !== 1) throw new Error(`replay/watchdog order: ${log.join('/')}`)
  await player.getByRole('button', { name: '抽屜進出' }).click()
  await page.getByRole('button', { name: '卸載轉場播放器' }).click()
  log = await events(page, '轉場事件紀錄')
  if (log.filter(value => value === 'drawer:cancel').length !== 1 || log.filter(value => value === 'drawer:complete').length) throw new Error(`unmount termination: ${log.join('/')}`)
  await page.getByLabel('Quiet').check()
  await page.getByRole('button', { name: '重新掛載轉場播放器' }).click()
  await page.locator('section.card').filter({ has: page.getByRole('heading', { name: '轉場播放器' }) }).getByRole('button', { name: '重播', exact: true }).click()
  log = await events(page, '轉場事件紀錄')
  if (log.filter(value => value === 'page:complete').length !== 2) throw new Error(`Quiet still completion: ${log.join('/')}`)

  await page.goto('http://127.0.0.1:5174/?ui-review=hatch', { waitUntil: 'networkidle' })
  const hatch = page.locator('section.card').filter({ has: page.getByRole('heading', { name: '首次目標 · 孵化展示' }) })
  await hatch.getByRole('button', { name: '開始孵化' }).click()
  await hatch.getByRole('button', { name: '取消／返回' }).click()
  let hatchLog = await events(page, '孵化事件紀錄')
  if (hatchLog.filter(value => value.endsWith(':start')).length !== 1 || hatchLog.filter(value => value.endsWith(':cancel')).length !== 1) throw new Error(`hatch cancel: ${hatchLog.join('/')}`)
  await hatch.getByRole('button', { name: '開始孵化' }).click()
  await page.getByLabel('提供虛構已確認回執').uncheck() // 卸載舊回執，不允許晚到 complete。
  hatchLog = await events(page, '孵化事件紀錄')
  if (hatchLog.filter(value => value.endsWith(':cancel')).length !== 2) throw new Error(`receipt unmount: ${hatchLog.join('/')}`)
  await page.waitForTimeout(1300)
  if ((await events(page, '孵化事件紀錄')).some(value => value.endsWith(':complete'))) throw new Error('old receipt completed after unmount')
  await page.getByLabel('提供虛構已確認回執').check()
  await page.getByLabel('減少動效').check()
  await page.locator('section.card').filter({ has: page.getByRole('heading', { name: '首次目標 · 孵化展示' }) }).getByRole('button', { name: '開始孵化' }).click()
  hatchLog = await events(page, '孵化事件紀錄')
  if (hatchLog.filter(value => value.endsWith(':complete')).length !== 1) throw new Error(`reduced hatch not immediately complete: ${hatchLog.join('/')}`)
  await page.close()
  console.log('v1.1 lifecycle QA passed: replay watchdog, unmount cancel, receipt switch and reduced static completion.')
} finally { await browser.close() }
