import { chromium } from 'playwright' // 真 Chrome 驗證本機真 Blob 與校對文字的 owner 隔離。
import path from 'node:path' // 選用套件內既有小 PNG 作測試素材。

const browser = await chromium.launch({ headless: true, executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe' })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  await page.goto('http://127.0.0.1:5174/?ui-review=record', { waitUntil: 'networkidle' })
  const media = page.locator('section.card').filter({ has: page.getByRole('heading', { name: '本機素材與上傳' }) })
  const draft = page.locator('section.card').filter({ has: page.getByRole('heading', { name: 'v1.1 本機草稿持久化' }) })
  const first = path.join(process.cwd(), 'assets/shared-art/lifeworld-fullkit-shared-art/exports/lw-app-icon-v1@48.png')
  const second = path.join(process.cwd(), 'assets/shared-art/lifeworld-fullkit-shared-art/exports/lw-app-icon-v1@192.png')
  await media.locator('input[type=file]').setInputFiles(first)
  await media.locator('input[type=file]').setInputFiles({ name: 'oversize.png', mimeType: 'image/png', buffer: Buffer.alloc(2 * 1024 * 1024 + 1) })
  await page.getByText('本 fixture 限 2 MiB', { exact: false }).waitFor() // 錯誤狀態顯示在下方校對卡。
  if (!await media.getByText('lw-app-icon-v1@48.png', { exact: false }).count()) throw new Error('fixture capacity failure discarded the previous source')
  await media.locator('input[type=file]').setInputFiles(first) // 可用檔案仍可恢復。
  await media.getByRole('button', { name: '明確上傳 fixture' }).click()
  await media.getByText('上傳回執：fixture-material-receipt', { exact: false }).waitFor()
  await media.getByRole('button', { name: '辨識 fixture' }).click()
  await page.getByText('辨識原文（唯讀）：這是虛構辨識原文', { exact: false }).waitFor()
  await page.getByRole('textbox', { name: '人工校對文字' }).fill('實際選檔後的人工校對')
  await page.getByRole('button', { name: '標記人工核對' }).click()
  await page.getByRole('button', { name: '套用文字與素材到本機草稿' }).click()
  await draft.getByText('已套用 MediaDemo').waitFor()
  if (await draft.getByRole('textbox', { name: '本機草稿文字' }).inputValue() !== '實際選檔後的人工校對') throw new Error('edited text not copied')
  if (!await draft.getByRole('img', { name: '本機草稿圖片預覽' }).isVisible()) throw new Error('real Blob preview missing before save')
  await draft.getByRole('combobox', { name: '故障 fixture' }).selectOption('save-failure')
  await draft.getByRole('button', { name: '保存本機草稿' }).click()
  await draft.getByRole('alert').getByText('保存失敗', { exact: false }).waitFor()
  if (!await draft.getByRole('img', { name: '本機草稿圖片預覽' }).isVisible()) throw new Error('save failure discarded real Blob')
  await draft.getByRole('combobox', { name: '故障 fixture' }).selectOption('normal')
  await draft.getByRole('button', { name: '保存本機草稿' }).click()
  await draft.getByText('已存本機草稿', { exact: false }).waitFor()
  await page.reload({ waitUntil: 'networkidle' })
  const saved = page.locator('section.card').filter({ has: page.getByRole('heading', { name: 'v1.1 本機草稿持久化' }) })
  await saved.getByText('已回讀本機草稿', { exact: false }).waitFor()
  if (await saved.getByRole('textbox', { name: '本機草稿文字' }).inputValue() !== '實際選檔後的人工校對') throw new Error('edited text did not persist')
  if (!await saved.getByText('辨識原文（唯讀）：這是虛構辨識原文', { exact: false }).count()) throw new Error('original transcript did not persist separately')
  if (!await saved.getByRole('img', { name: '本機草稿圖片預覽' }).isVisible()) throw new Error('true Blob did not persist')
  await saved.screenshot({ path: path.join(process.cwd(), 'docs', 'qa', 'v1_1', 'media-real-blob-restored-390x844.png') }) // 真實 fixture 預覽與校對的回讀畫面。
  await saved.getByRole('combobox', { name: '示範 owner' }).selectOption('demo-owner-b')
  await saved.getByText('此 owner 尚無本機草稿').waitFor()
  if (await saved.getByRole('img', { name: '本機草稿圖片預覽' }).count()) throw new Error('Blob leaked to owner B')
  await saved.getByRole('combobox', { name: '示範 owner' }).selectOption('demo-owner-a')
  await saved.getByRole('img', { name: '本機草稿圖片預覽' }).waitFor()
  const mediaAgain = page.locator('section.card').filter({ has: page.getByRole('heading', { name: '本機素材與上傳' }) })
  await mediaAgain.locator('input[type=file]').setInputFiles(second)
  await page.getByRole('textbox', { name: '人工校對文字' }).fill('第二份素材的校對')
  await page.getByRole('button', { name: '套用文字與素材到本機草稿' }).click()
  await saved.getByRole('combobox', { name: '故障 fixture' }).selectOption('link-failure')
  await saved.getByRole('button', { name: '保存本機草稿' }).click()
  await saved.getByRole('alert').getByText('素材連結失敗', { exact: false }).waitFor()
  await page.reload({ waitUntil: 'networkidle' })
  const pending = page.locator('section.card').filter({ has: page.getByRole('heading', { name: 'v1.1 本機草稿持久化' }) })
  await pending.getByRole('button', { name: '重試素材連結' }).waitFor()
  if (await pending.getByRole('textbox', { name: '本機草稿文字' }).inputValue() !== '第二份素材的校對') throw new Error('text lost on link failure')
  if (!await pending.getByRole('img', { name: '本機草稿圖片預覽' }).isVisible()) throw new Error('Blob lost on link failure')
  await pending.getByRole('button', { name: '重試素材連結' }).click()
  await pending.getByText('的素材已連結', { exact: false }).waitFor()
  await page.getByRole('button', { name: '選名片 fixture' }).click()
  await page.getByRole('button', { name: '複製名片到本機草稿' }).click()
  if (await pending.getByRole('textbox', { name: '本機草稿文字' }).inputValue() !== '名片待核對：虛構名片.png') throw new Error('card copy did not make a local draft')
  await pending.getByRole('button', { name: '保存本機草稿' }).click()
  await pending.getByText('已存本機草稿', { exact: false }).waitFor()
  await page.reload({ waitUntil: 'networkidle' })
  if (await page.getByRole('textbox', { name: '本機草稿文字' }).inputValue() !== '名片待核對：虛構名片.png') throw new Error('local card draft did not persist')
  console.log('Media persistence QA passed: real image Blob + reviewed text survive reload, owner isolation, partial link failure and retry.')
} finally { await browser.close() }
